// Command bundlegen keeps hack/authz-dev/bundle/policies.cedar in step with
// api/openapi.yaml and checks that the bundle loads. Cedar has no action
// wildcards and LocalBundle no action groups, so each role's policy lists its
// actions:
//
//	reader    every get* and list* operation
//	writer    every create*, update* and delete* operation
//	operator  every action
//
// An operation with any other verb fails the run, so a new one gets a decision.
//
//	go run ./hack/authz-dev/bundlegen -write   # regenerate policies.cedar, then check
//	go run ./hack/authz-dev/bundlegen          # check only: fails if policies.cedar is stale
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/dsx-ai-factory/nvke/auth/authz/localbundle"

	"github.com/dsx-ai-factory/nvke/controller/api"
)

// issuers are the issuer names the dev environment's authN config declares.
func issuers() []string { return []string{"local-kubernetes", "idp-a", "idp-b"} }

// resourceTypes are the resource types the controller's middleware asks about.
func resourceTypes() []string {
	return []string{"Cluster", "NodePool", "NodeSet", "Node", "Collection"}
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "bundlegen:", err)
		os.Exit(1)
	}
}

func run() error {
	dir := flag.String("dir", "hack/authz-dev/bundle", "bundle directory")
	write := flag.Bool("write", false, "rewrite policies.cedar from the spec")
	flag.Parse()

	actions, err := operationIDs()
	if err != nil {
		return err
	}
	policies, err := render(actions)
	if err != nil {
		return err
	}

	path := filepath.Join(*dir, "policies.cedar")
	if *write {
		if err := os.WriteFile(path, policies, 0o644); err != nil { //nolint:gosec // a committed, public file
			return err
		}
	} else {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, policies) {
			return fmt.Errorf("%s is stale against api/openapi.yaml; run go run ./hack/authz-dev/bundlegen -write", path)
		}
	}

	if _, err := localbundle.New(localbundle.Options{
		Dir:           *dir,
		Issuers:       issuers(),
		Actions:       actions,
		ResourceTypes: resourceTypes(),
	}); err != nil {
		return fmt.Errorf("the bundle in %s does not load: %w", *dir, err)
	}
	fmt.Fprintf(os.Stdout, "bundle in %s loads: %d actions, issuers %v\n", *dir, len(actions), issuers())
	return nil
}

// operationIDs returns every operationId in the embedded spec, sorted. The
// generator capitalizes each one in the embedded copy (CreateCluster), so the
// first letter is lowered back to the spelling in api/openapi.yaml.
func operationIDs() ([]string, error) {
	spec, err := api.GetSwagger()
	if err != nil {
		return nil, fmt.Errorf("load the embedded spec: %w", err)
	}
	var ids []string
	for _, item := range spec.Paths.Map() {
		for _, op := range item.Operations() {
			if id := op.OperationID; id != "" {
				ids = append(ids, strings.ToLower(id[:1])+id[1:])
			}
		}
	}
	slices.Sort(ids)
	return slices.Compact(ids), nil
}

func render(actions []string) ([]byte, error) {
	var read, write []string
	for _, a := range actions {
		switch {
		case strings.HasPrefix(a, "get"), strings.HasPrefix(a, "list"):
			read = append(read, a)
		case strings.HasPrefix(a, "create"), strings.HasPrefix(a, "update"), strings.HasPrefix(a, "delete"):
			write = append(write, a)
		default:
			return nil, fmt.Errorf("operation %q is neither a read (get, list) nor a write (create, update, delete); classify it in bundlegen", a)
		}
	}

	var b bytes.Buffer
	b.WriteString("// SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n")
	b.WriteString("// SPDX-License-Identifier: Apache-2.0\n\n")
	b.WriteString("// Generated by go run ./hack/authz-dev/bundlegen -write from api/openapi.yaml. Do not edit.\n\n")
	permit(&b, "reader-may-read", "reader", read)
	b.WriteString("\n")
	permit(&b, "writer-may-write", "writer", write)
	b.WriteString("\n")
	b.WriteString("@id(\"operator-may-do-anything\")\n")
	b.WriteString("permit(principal in NVKE::Role::\"operator\", action, resource);\n")
	return b.Bytes(), nil
}

func permit(b *bytes.Buffer, id, role string, actions []string) {
	fmt.Fprintf(b, "@id(%q)\n", id)
	fmt.Fprintf(b, "permit(\n  principal in NVKE::Role::%q,\n  action in [\n", role)
	for i, a := range actions {
		sep := ","
		if i == len(actions)-1 {
			sep = ""
		}
		fmt.Fprintf(b, "    NVKE::Action::%q%s\n", a, sep)
	}
	b.WriteString("  ],\n  resource\n);\n")
}
